CREATE TABLE IF NOT EXISTS users(id INTEGER PRIMARY KEY,username TEXT UNIQUE,pw TEXT,name TEXT,bio TEXT DEFAULT '',color TEXT DEFAULT '#6d5efc',avatar TEXT);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,user INT);
CREATE TABLE IF NOT EXISTS servers(id INTEGER PRIMARY KEY,name TEXT,owner INT,invite TEXT);
CREATE TABLE IF NOT EXISTS members(server INT,user INT,PRIMARY KEY(server,user));
CREATE TABLE IF NOT EXISTS roles(id INTEGER PRIMARY KEY,server INT,name TEXT,color TEXT,perms INT);
CREATE TABLE IF NOT EXISTS member_roles(role INT,user INT,PRIMARY KEY(role,user));
CREATE TABLE IF NOT EXISTS channels(id INTEGER PRIMARY KEY,server INT,name TEXT,type TEXT);
CREATE TABLE IF NOT EXISTS dms(id INTEGER PRIMARY KEY,a INT,b INT);
CREATE TABLE IF NOT EXISTS messages(id INTEGER PRIMARY KEY,room TEXT,user INT,body TEXT,ts INT,file TEXT,edited INT DEFAULT 0);
CREATE INDEX IF NOT EXISTS msg_room ON messages(room,id);
CREATE TABLE IF NOT EXISTS reacts(msg INT,user INT,emo TEXT,PRIMARY KEY(msg,user,emo));
CREATE TABLE IF NOT EXISTS bans(server INT,user INT,PRIMARY KEY(server,user));
CREATE TABLE IF NOT EXISTS friends(a INT,b INT,ok INT DEFAULT 0,PRIMARY KEY(a,b));
CREATE TABLE IF NOT EXISTS vsig(id INTEGER PRIMARY KEY,room TEXT,frm INT,too INT,data TEXT);
CREATE TABLE IF NOT EXISTS vpres(room TEXT,user INT,ts INT,PRIMARY KEY(room,user));
